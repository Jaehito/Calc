package com.calc.expense

/**
 * 지출 이름을 보고 카테고리를 짐작한다. 네트워크·LLM 없이 낱말 규칙만으로 판단한다 —
 * 잠금화면에서 타이핑하는 즉시 반응해야 하기 때문이다.
 *
 * 규칙은 [Categories.DEFAULT] 열 개 이름에 고정돼 있다. 사용자가 설정에서 그 칩의 이름을
 * 바꾸면([classify] 의 [categories] 인자에 그 이름이 없으면) 그 규칙은 조용히 꺼진다 —
 * 존재하지 않는 칩을 자동으로 켤 수는 없기 때문이다. «기타» 는 규칙이 없다 — 무엇이든
 * «기타» 로 밀어넣는 건 분류가 아니다.
 *
 * Android 에 의존하지 않아 단위 테스트로 고정한다.
 */
object CategoryClassifier {

    /** (카테고리, 그 안에 있으면 매칭으로 보는 낱말들). 앞에 있는 규칙이 우선한다. */
    private val RULES: List<Pair<String, List<String>>> = listOf(
        "카페" to listOf(
            "커피", "카페", "스타벅스", "이디야", "투썸", "메가커피", "빽다방", "컴포즈",
            "라떼", "아메리카노", "디저트", "케이크", "베이커리", "빵집",
        ),
        "식비" to listOf(
            "점심", "저녁", "아침", "식당", "국밥", "김밥", "분식", "치킨", "피자", "족발",
            "보쌈", "배달", "떡볶이", "라면", "삼겹살", "국수", "도시락", "회식", "고기",
        ),
        "마트" to listOf(
            "마트", "장보기", "이마트", "홈플러스", "롯데마트", "편의점", "gs25", "cu",
            "세븐일레븐", "코스트코", "슈퍼",
        ),
        "교통" to listOf(
            "택시", "버스", "지하철", "주유", "주유소", "주차", "기차", "ktx", "srt",
            "고속버스", "톨게이트", "하이패스", "따릉이",
        ),
        "생활" to listOf(
            "다이소", "세제", "휴지", "세탁", "생활용품", "청소", "수건", "쓰레기봉투",
        ),
        "건강" to listOf(
            "약국", "병원", "한의원", "치과", "영양제", "마사지", "헬스장", "필라테스", "정형외과",
        ),
        "문화" to listOf(
            "영화", "공연", "전시", "도서", "서점", "넷플릭스", "유튜브프리미엄", "콘서트", "박물관", "책",
        ),
        "패션" to listOf(
            "옷", "신발", "가방", "화장품", "미용실", "네일", "액세서리", "안경",
        ),
        "주거" to listOf(
            "월세", "관리비", "전기세", "전기요금", "가스비", "수도세", "공과금", "통신비", "보험료",
        ),
    )

    /**
     * [name] 에서 카테고리를 짐작한다. 맞는 규칙이 없거나, 맞는 카테고리가 지금 칩 목록
     * ([categories]) 에 없으면 null — 그러면 화면은 «없음» 을 유지한다.
     */
    fun classify(name: String, categories: List<String>): String? {
        val lower: String = name.lowercase()
        for ((category, keywords) in RULES) {
            if (category !in categories) continue
            if (keywords.any { lower.contains(it.lowercase()) }) return category
        }
        return null
    }
}
